export const OPS_STRINGS: Readonly<Record<Locale, Dict>> = {
  'zh-TW': zhTW,
  'zh-CN': zhCN,
  en,
  ja,
  vi,
  th,
  ko,
};

export type OpsT = (key: OpsStringKey, params?: Record<string, string | number>) => string;

export function opsT(key: OpsStringKey, params?: Record<string, string | number>): string {
  const raw = (OPS_STRINGS[getCurrentLocale()] ?? zhTW)[key] ?? zhTW[key];
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name: string) => (params[name] !== undefined ? String(params[name]) : m));
}

/** 跟著全站語系切換重新 render（借用 useT 的訂閱）。 */
export function useOpsT(): OpsT {
  useT();
  return useCallback(opsT, []);
}
